"""
Abstract Base Class for LLM providers in the AI Itinerary and Travel Recommendation Layer.
"""
from abc import ABC, abstractmethod
import json
import re
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field

from app.core.exceptions import (
    LLMProviderError,
    LLMAuthenticationError,
    LLMQuotaExceededError,
    LLMTimeoutError,
    LLMResponseMalformedError,
)

class LLMResponse(BaseModel):
    """Normalized response container from any LLM provider."""
    text: str = Field(..., description="Raw text generated by the model")
    model: str = Field(..., description="The model name that generated the response")
    provider: str = Field(..., description="Identifier of the provider (e.g. gemini, mock, groq)")
    usage: Optional[Dict[str, Any]] = Field(default=None, description="Token usage metrics if reported")
    structured_data: Optional[Dict[str, Any]] = Field(default=None, description="Parsed structured data if available")

class LLMProvider(ABC):
    """
    Standardized asynchronous interface for all LLM providers.
    All travel planning and itinerary generation services depend on this abstract interface.
    """

    name: str = "base"

    @abstractmethod
    async def generate_text(
        self,
        prompt: str,
        settings: Optional[Dict[str, Any]] = None
    ) -> LLMResponse:
        """
        Generates text asynchronously from a given prompt and generation parameters.
        Must normalize provider output into an LLMResponse.
        """
        pass

    @abstractmethod
    async def generate_structured(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        expected_root_key: Optional[str] = None,
        settings: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Generates structured JSON conforming to travel planner schemas.
        Must handle parsing, cleaning of code fences, and error wrapping.
        """
        pass

    @abstractmethod
    async def check_health(self) -> Dict[str, Any]:
        """
        Checks connectivity, API key validity, and configured model status.
        """
        pass

    def extract_json(self, text: str) -> Dict[str, Any]:
        """
        Safely extracts and parses JSON from raw LLM output, stripping markdown
        fences and attempting outermost object isolation.
        """
        cleaned = text.strip()
        # 1. Match ```json ... ``` or ``` ... ```
        json_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", cleaned)
        if json_match:
            cleaned = json_match.group(1).strip()
        else:
            # 2. Slice between first { and last }
            start_bracket = cleaned.find("{")
            end_bracket = cleaned.rfind("}")
            if start_bracket != -1 and end_bracket != -1 and end_bracket > start_bracket:
                cleaned = cleaned[start_bracket:end_bracket + 1]

        # 3. Clean trailing commas before close braces
        cleaned = re.sub(r",\s*([\]}])", r"\1", cleaned)

        try:
            return json.loads(cleaned)
        except json.JSONDecodeError as err:
            raise LLMResponseMalformedError(
                f"Failed to parse LLM response as valid JSON: {err}. Raw excerpt: {cleaned[:250]}"
            )
